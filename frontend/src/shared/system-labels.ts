export function systemValueLabel(value: string, t: (key: MessageKey) => string) {
  return value.split(' · ').map(part => {
    const name = part.replace(/^mcp__helm__/, '');
    const label = valueLabels[name];
    return label ? t(label) : part;
  }).join(' · ');
}
