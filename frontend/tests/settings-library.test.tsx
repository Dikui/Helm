import { afterEach, expect, test } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { App } from '../src/App.js';
const { uiFixture }: typeof import('../../tests/ui-fixture.js') = await import('../../dist/tests/' + 'ui-fixture.js');
let daemon: Awaited<ReturnType<typeof uiFixture>> | undefined;
afterEach(async () => { cleanup(); await daemon?.close(); daemon = undefined; localStorage.clear(); });
const change = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label, { selector: 'input,select,textarea' }), { target: { value } });

test('库分区列出类型和引用 Agent，只显示密钥键名，删除被引用条目时展示结构化错误', async () => {
  daemon = await uiFixture();
  await daemon.call('register-mcp', { name: 'remote', config: { type: 'http', url: 'https://tools.example.invalid/mcp', headers: { Authorization: 'Bearer hidden-http' } } });
  await daemon.call('register-mcp', { name: 'local', config: { type: 'stdio', command: 'probe', args: ['hidden-arg'], env: { TOKEN: 'hidden-env' } } });
  const agent = (await daemon.call('list-agents')).result.find((item: any) => item.id === 'claude-executor');
  await daemon.call('save-agent', { id: agent.id, mode: 'update', baseRevision: agent.revision, config: { ...agent.config, mcp: ['remote'] }, prompt: agent.prompt });
  window.history.replaceState(null, '', '/settings/agents');
  render(<App baseUrl={daemon.url} />);
  fireEvent.click(within(screen.getByRole('navigation', { name: '设置' })).getByRole('link', { name: '库' }));
  const remote = await screen.findByRole('article', { name: 'MCP · HTTP remote' });
  expect(within(remote).getByRole('link', { name: 'claude-executor' }).getAttribute('href')).toBe('/settings/agents/claude-executor');
  expect(within(remote).getByText('Authorization')).toBeTruthy();
  const local = screen.getByRole('article', { name: 'MCP · stdio local' });
  expect(within(local).getByText('TOKEN')).toBeTruthy();
  expect(screen.queryByText(/hidden-http|hidden-env|hidden-arg/)).toBeNull();
  fireEvent.click(within(remote).getByRole('button', { name: '删除' }));
  const error = await within(remote).findByRole('alert');
  expect(error.textContent).toContain('LIBRARY_ENTRY_IN_USE');
  expect(within(error).getByRole('link', { name: 'claude-executor' })).toBeTruthy();
  fireEvent.click(within(local).getByRole('button', { name: '删除' }));
  await within(screen.getByRole('region', { name: '库' })).findByText('已删除');
  await waitFor(() => expect(screen.queryByRole('article', { name: 'MCP · stdio local' })).toBeNull());
  expect((await daemon.call('list-library')).result.map((entry: any) => entry.name)).toEqual(['remote']);
});

test('从本地目录安装 skill，可省略或指定名字，同名和无效路径错误保留输入', async () => {
  daemon = await uiFixture();
  const source = join(daemon.directory, 'local-skill');
  await mkdir(source);
  await writeFile(join(source, 'SKILL.md'), '本地技能');
  window.history.replaceState(null, '', '/settings/library');
  render(<App baseUrl={daemon.url} />);
  await screen.findByText('库里还没有条目。安装一个 skill 或登记一个 MCP 开始使用。');
  const form = screen.getByRole('form', { name: '安装 skill' });
  const submit = () => fireEvent.click(within(form).getByRole('button', { name: '安装 skill' }));
  submit();
  expect(screen.getByLabelText('本地目录路径').getAttribute('aria-invalid')).toBe('true');
  expect(document.activeElement).toBe(screen.getByLabelText('本地目录路径'));
  change('本地目录路径', source); submit();
  await screen.findByRole('article', { name: 'skill local-skill' });
  change('本地目录路径', source); change('skill 名字（可选）', 'renamed'); submit();
  await screen.findByRole('article', { name: 'skill renamed' });
  change('本地目录路径', source); change('skill 名字（可选）', 'renamed'); submit();
  expect((await within(form).findByRole('alert')).textContent).toContain('已存在');
  expect((screen.getByLabelText('skill 名字（可选）') as HTMLInputElement).value).toBe('renamed');
  change('本地目录路径', join(daemon.directory, 'missing')); change('skill 名字（可选）', 'missing'); submit();
  expect((await within(form).findByRole('alert')).textContent).toContain('不能安装 skill');
  expect((screen.getByLabelText('本地目录路径') as HTMLInputElement).value).toContain('missing');
  expect((await daemon.call('list-library')).result.map((entry: any) => entry.name)).toEqual(['local-skill', 'renamed']);
  const renamed = screen.getByRole('article', { name: 'skill renamed' });
  fireEvent.click(within(renamed).getByRole('button', { name: '删除' }));
  await waitFor(() => expect(screen.queryByRole('article', { name: 'skill renamed' })).toBeNull());
  expect((await daemon.call('list-library')).result.map((entry: any) => entry.name)).toEqual(['local-skill']);
});

test('勾选覆盖同名 skill 时请求带 replace: true，成功后重置勾选并更新内容', async () => {
  daemon = await uiFixture();
  const source = join(daemon.directory, 'shared');
  await mkdir(source);
  await writeFile(join(source, 'SKILL.md'), '旧版本');
  expect((await daemon.call('install-skill', { path: source })).ok).toBe(true);
  await writeFile(join(source, 'SKILL.md'), '新版本');
  const requests: Record<string, unknown>[] = [];
  const transport: typeof fetch = (url, options) => {
    if (String(url).endsWith('/api/install-skill')) requests.push(JSON.parse(String(options?.body)));
    return fetch(url, options);
  };
  window.history.replaceState(null, '', '/settings/library');
  render(<App baseUrl={daemon.url} transport={transport} />);
  await screen.findByRole('article', { name: 'skill shared' });
  const form = screen.getByRole('form', { name: '安装 skill' });
  change('本地目录路径', source);
  fireEvent.click(within(form).getByRole('button', { name: '安装 skill' }));
  expect((await within(form).findByRole('alert')).textContent).toContain('库 skill shared 已存在');
  expect(requests).toEqual([{ path: source }]);
  const checkbox = within(form).getByRole('checkbox', { name: '覆盖同名 skill' }) as HTMLInputElement;
  expect(checkbox.checked).toBe(false);
  fireEvent.click(checkbox);
  fireEvent.click(within(form).getByRole('button', { name: '安装 skill' }));
  expect(checkbox.disabled).toBe(true);
  await within(form).findByText('已保存');
  expect(requests[1]).toEqual({ path: source, replace: true });
  expect(checkbox.checked).toBe(false);
  expect(await readFile(join(daemon.directory, 'data', 'library', 'skills', 'shared', 'SKILL.md'), 'utf8')).toBe('新版本');
  fireEvent.click(screen.getByRole('button', { name: 'EN' }));
  expect(screen.getByRole('checkbox', { name: 'Replace skill with the same name' })).toBeTruthy();
});

test('登记 HTTP 和 stdio MCP，校验 JSON 输入、遮罩密钥并在失败后保留输入', async () => {
  daemon = await uiFixture();
  window.history.replaceState(null, '', '/settings/library');
  render(<App baseUrl={daemon.url} />);
  const form = await screen.findByRole('form', { name: '登记 MCP' });
  const submit = () => fireEvent.click(within(form).getByRole('button', { name: '登记 MCP' }));
  change('MCP 名字', 'remote'); change('URL', 'not-a-url'); submit();
  expect(screen.getByLabelText('URL').getAttribute('aria-invalid')).toBe('true');
  expect(document.activeElement).toBe(screen.getByLabelText('URL'));
  change('URL', 'https://tools.example.invalid/mcp');
  const headers = screen.getByLabelText('请求头（JSON 对象，可选）') as HTMLInputElement;
  expect(headers.type).toBe('password');
  change('请求头（JSON 对象，可选）', '{"Authorization":42}'); submit();
  expect(headers.getAttribute('aria-invalid')).toBe('true');
  const description = headers.getAttribute('aria-describedby');
  expect(document.getElementById(description!)?.textContent).toContain('JSON 对象');
  change('请求头（JSON 对象，可选）', '{"Authorization":"Bearer hidden-http"}');
  fireEvent.click(screen.getByRole('button', { name: '显示请求头' }));
  expect(headers.type).toBe('text');
  fireEvent.click(screen.getByRole('button', { name: '隐藏请求头' }));
  expect(headers.type).toBe('password');
  submit();
  expect(form.getAttribute('aria-busy')).toBe('true');
  expect((within(form).getByRole('button', { name: '登记 MCP' }) as HTMLButtonElement).disabled).toBe(true);
  const remote = await screen.findByRole('article', { name: 'MCP · HTTP remote' });
  expect(within(remote).getByText('Authorization')).toBeTruthy();
  expect(remote.textContent).not.toContain('hidden-http');
  change('MCP 名字', 'local'); change('传输方式', 'stdio'); change('命令', 'probe');
  change('参数（JSON 字符串数组，可选）', '[42]'); submit();
  expect(screen.getByLabelText('参数（JSON 字符串数组，可选）').getAttribute('aria-invalid')).toBe('true');
  change('参数（JSON 字符串数组，可选）', '["--label","two words",""]');
  const env = screen.getByLabelText('环境变量（JSON 对象，可选）') as HTMLInputElement;
  expect(env.type).toBe('password');
  change('环境变量（JSON 对象，可选）', '[]'); submit();
  expect(env.getAttribute('aria-invalid')).toBe('true');
  change('环境变量（JSON 对象，可选）', '{"TOKEN":"hidden-env"}'); submit();
  const local = await screen.findByRole('article', { name: 'MCP · stdio local' });
  expect(within(local).getByText('TOKEN')).toBeTruthy();
  expect(local.textContent).not.toContain('hidden-env');
  expect(JSON.parse(await readFile(join(daemon.directory, 'data', 'library', 'mcp', 'local.json'), 'utf8'))).toEqual({
    type: 'stdio', command: 'probe', args: ['--label', 'two words', ''], env: { TOKEN: 'hidden-env' },
  });
  change('MCP 名字', 'local'); change('命令', 'other-probe'); submit();
  expect((await within(form).findByRole('alert')).textContent).toContain('已存在');
  expect((screen.getByLabelText('命令') as HTMLInputElement).value).toBe('other-probe');
  fireEvent.click(screen.getByRole('button', { name: 'EN' }));
  expect(screen.getByRole('region', { name: 'Library' })).toBeTruthy();
  expect(screen.getByRole('form', { name: 'Install skill' })).toBeTruthy();
  expect(screen.getByRole('form', { name: 'Register MCP' })).toBeTruthy();
  expect(screen.getByRole('button', { name: 'Show environment variables' })).toBeTruthy();
  change('Environment variables (JSON object, optional)', 'null');
  fireEvent.click(within(form).getByRole('button', { name: 'Register MCP' }));
  expect(screen.getByText('Enter a JSON object with string values, such as {"KEY":"value"}.')).toBeTruthy();
  // Both forms share one navigation guard, so editing both never shows two prompts.
  change('Local directory path', '/unfinished');
  fireEvent.click(within(screen.getByRole('navigation', { name: 'Settings' })).getByRole('link', { name: 'Projects' }));
  expect(window.location.pathname).toBe('/settings/library');
  fireEvent.click(screen.getByRole('button', { name: 'Keep editing' }));
  expect((screen.getByLabelText('Command') as HTMLInputElement).value).toBe('other-probe');
});
